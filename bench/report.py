"""Render bench/results/*.json into a markdown report.

Usage: python3 bench/report.py
Writes bench/results/report.md
"""
import glob
import json
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")

ORDER = ["bgse", "rea_gated", "rea", "tpe", "reinforce", "random"]
LABEL = {
    "bgse": "BGSE (1+lambda, gated)",
    "rea_gated": "REA + gate (ablation)",
    "rea": "REA",
    "tpe": "TPE",
    "reinforce": "REINFORCE",
    "random": "Random",
}


def load(path):
    with open(path) as f:
        return json.load(f)


def stats(blob, method):
    runs = blob["runs"][method]
    ok = [r for r in runs if r["ok"]]
    ps = [r["params"] for r in ok]
    ev = [r["eval_to_first"] for r in ok if r["eval_to_first"] is not None]
    return {
        "n": len(runs),
        "ok": len(ok),
        "median": float(np.median(ps)) if ps else float("nan"),
        "mean": float(np.mean(ps)) if ps else float("nan"),
        "first": float(np.median(ev)) if ev else float("nan"),
    }


def main():
    files = sorted(glob.glob(os.path.join(RES, "nats_t*_b*.json")))
    out = ["# Budget-aware width search on NATS-Bench / CIFAR-10", ""]
    out += ["Generated by `bench/report.py` from the JSON records in this directory.",
            ""]
    out += ["Space: NATS-Bench size (5 stages x 8 widths, 32,768 architectures).",
            "Metric: CIFAR-10 test accuracy after 90 epochs, precomputed by the benchmark.",
            "Objective: lexicographic - feasible first (accuracy >= tau), then fewest parameters.",
            "Budget: architecture evaluations, identical for every method.",
            "Seeds: 30 per cell.", ""]

    for path in files:
        blob = load(path)
        tau, budget = blob["tau"], blob["budget"]
        opt = blob["optimum"]["params"]
        out += [f"## tau = {tau}, budget = {budget}", "",
                f"Global optimum in this space: **{opt:.4f} M** parameters "
                f"(accuracy {blob['optimum']['acc']:.2f}%).", ""]
        out += ["| method | success | median params (M) | mean | gap to optimum | median evals to first feasible |",
                "|---|---|---|---|---|---|"]
        for m in ORDER:
            s = stats(blob, m)
            gap = f"{(s['median'] / opt - 1) * 100:+.1f}%" if s["ok"] else "-"
            out.append(
                f"| {LABEL[m]} | {s['ok']}/{s['n']} | {s['median']:.4f} | "
                f"{s['mean']:.4f} | {gap} | {s['first']:.1f} |")
        out.append("")

    out += ["## Reading", "",
            "- The **gate is a small, consistent win inside a population search**:",
            "  `REA + gate` beats plain `REA` on parameters at both budgets for tau=92",
            "  and at budget 100 for tau=93, though the two are tied at tau=93 / 300.",
            "- The **(1+lambda) elitist wrapper is the weak part**: BGSE stops improving",
            "  when the budget grows (tau=92: same median at 100 and 300 evaluations),",
            "  because it keeps the incumbent and every shrink from the boundary is",
            "  rejected. It is competitive only in the hardest cell at the small budget.",
            "- **TPE is the strongest** method here, which is expected in five",
            "  categorical dimensions with 100-300 samples.",
            "- The tabular benchmark has **no repair step**: accuracy is a table lookup,",
            "  so the mechanism that makes BGSE work in the demos (Lamarckian repair",
            "  after a structural change) cannot act. This table therefore measures the",
            "  search rule alone, not the full method.", ""]

    with open(os.path.join(RES, "report.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
